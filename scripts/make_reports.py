def copy_gallery(out: Path) -> list[str]:
    import sqlite3

    from core.fusion.chips import chip_file_at

    db = sqlite3.connect(ROOT / "data" / "khalij.db")
    copied = []
    for detection_id, stem, _ in GALLERY:
        row = db.execute(
            "select d.lon, d.lat, s.product_name from detections d join sar_scenes s "
            "on s.id = d.scene_id where d.id = ?",
            (detection_id,),
        ).fetchone()
        if row is None:
            continue
        path = chip_file_at(ROOT / "data" / "chips", row[2], row[0], row[1], "vv")
        if path is not None:
            shutil.copyfile(path, out / f"{stem}.png")
            copied.append(stem)
    return copied


