    run2 = test92["models"]["run2"]
    numbers = {"testModelSeconds": fa_num(run2["seconds_total"] / test92["scenes"], 1)}
    if bench.is_file():
        result = load(bench)
        numbers["benchSeconds"] = fa_num(result["median_s"], 1)
        numbers["benchMemory"] = fa_num(result["peak_memory_mb"])
        numbers["benchWindow"] = fa_num(result["window_px"])
    return numbers


