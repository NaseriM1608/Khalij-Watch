def sweep_rows(val_summary: dict, label: str) -> list[list[object]]:
    same = val_summary["sweep"][label]["same_cell"]["by_threshold"]
    nb = val_summary["sweep"][label]["neighbour_cells"]["by_threshold"]
    return [
        [
            float(t),
            round(same[t]["f1"], 4),
            round(nb[t]["f1"], 4),
            round(same[t]["recall_unmatched"], 4),
        ]
        for t in sorted(same, key=float)
    ]


