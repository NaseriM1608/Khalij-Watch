def dataset_table(index: Path) -> tuple[str, dict[str, str]]:
    chips, scenes, passes = Counter(), {}, set()
    with index.open(encoding="utf-8") as handle:
        for line in handle:
            r = json.loads(line)
            chips[(r["split"], r["supervision"], r["kind"])] += 1
            scenes.setdefault(r["split"], set()).add(r["scene"])
            passes.add((r["split"], r["area"], r["scene"]))
    splits = (("train", "آموزش"), ("val", "اعتبارسنجی"), ("test", "آزمون"))
    rows = []
    for key, name in splits:
        ais = chips[(key, "positive", "vessel")]
        dark = chips[(key, "positive", "unlabelled")]
        negatives = (
            chips[(key, "full_negative", "negative")] + chips[(key, "centre_negative", "negative")]
        )
        rows.append(
            [
                name,
                fa_num(len(scenes[key])),
                fa_num(sum(1 for s, _, _ in passes if s == key)),
                fa_num(ais),
                fa_num(dark),
                fa_num(negatives),
                fa_num(chips[(key, "ignore", "unlabelled")]),
            ]
        )
    total = sum(chips.values())
    table = latex_table(
        [
            "بخش",
            "تصویر",
            "گذر-محدوده",
            "مثبت با \\lr{AIS}",
            "مثبت بدون \\lr{AIS}",
            "منفی",
            "نادیده",
        ],
        rows,
        caption=(
            "داده‌های آموزش، اعتبارسنجی و آزمون در پنج محدوده مطالعاتی (\\lr{Sentinel-1A}، "
            "۲۰۲۴ تا ۲۰۲۵). تقسیم بر پایه تصویر است، نه تصادفی. «مثبت بدون \\lr{AIS}» "
            "آشکارسازی‌های \\lr{GFW} بدون تطبیق \\lr{AIS} است که در مدل نهایی مثبت گرفته شد."
        ),
        short="داده‌های آموزش، اعتبارسنجی و آزمون",
        label="tab:data",
    )
    numbers = {
        "dataChips": fa_num(total),
        "dataScenes": fa_num(sum(len(v) for v in scenes.values())),
        "dataPasses": fa_num(len(passes)),
        "dataTrainDark": fa_num(chips[("train", "positive", "unlabelled")]),
    }
    return table, numbers


def detector_rows(summary: dict, labels: Sequence[tuple[str, str]]) -> list[list[str]]:
    same, nb = summary["table"]["same_cell"]["all"], summary["table"]["neighbour_cells"]["all"]
    rows = []
    for key, name in labels:
        s, n = same[key], nb[key]
        rows.append(
            [
                name,
                fa_num(s["precision"], 3),
                fa_num(s["recall"], 3),
                fa_num(s["f1"], 3),
                fa_num(n["f1"], 3),
                fa_num(s["recall_ais_matched"], 3),
                fa_num(s["recall_unmatched"], 3),
            ]
        )
    return rows


