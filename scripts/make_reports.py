def _number(value: float, digits: int) -> str:
    """Latin digits, «٫» as the decimal separator and «٬» between thousands."""
    return f"{value:,.{digits}f}".replace(",", "٬").replace(".", "٫").replace("-", MINUS)


def fa_num(value: float, digits: int = 0) -> str:
    """A number for the Persian text, kept left to right."""
    return f"\\LRE{{{_number(value, digits)}}}"


def fa_signed(value: float, digits: int = 3) -> str:
    """A difference with its sign; one that rounds to zero has none."""
    rounded = round(value, digits)
    if rounded == 0:
        return fa_num(0.0, digits)
    sign = "+" if rounded > 0 else MINUS
    return f"\\LRE{{{sign}{_number(abs(rounded), digits)}}}"


def fa_interval(low: float, high: float, digits: int = 3) -> str:
    """«low تا high»: brackets inside \\LRE would be mirrored by the RTL font."""
    return f"{fa_signed(low, digits)} تا {fa_signed(high, digits)}"


def lr(text: str) -> str:
    """Latin text inside the Persian document (XePersian's \\lr)."""
    for char, escaped in LATEX_SPECIAL.items():
        text = text.replace(char, escaped)
    return f"\\lr{{{text}}}"


def latex_table(
    header: Sequence[str],
    rows: Sequence[Sequence[str]],
    *,
    caption: str,
    short: str,
    label: str,
) -> str:
    """A booktabs table; XePersian lays its columns out right to left.

    ``short`` is the caption in the list of tables; a table wider than the text
    is scaled down to fit (adjustbox ``max width``), never up.
    """
    spec = "l" + "c" * (len(header) - 1)
    lines = [
        "\\begin{table}[htbp]",
        "\\centering",
        "\\small",
        "\\begin{adjustbox}{max width=\\textwidth}",
        f"\\begin{{tabular}}{{{spec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
        *(" & ".join(row) + " \\\\" for row in rows),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{adjustbox}",
        f"\\caption[{short}]{{{caption}}}",
        f"\\label{{{label}}}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def macros(values: Mapping[str, str]) -> str:
    """\\newcommand per number; TeX control words are letters only."""
    bad = [name for name in values if not (name.isascii() and name.isalpha())]
    if bad:
        raise ValueError(f"macro names must be letters only: {', '.join(bad)}")
    header = "% Generated by scripts/make_reports.py: numbers quoted in the chapters.\n"
    return header + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items())


def write_csv(path: Path, header: Sequence[str], rows: Sequence[Sequence[object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


