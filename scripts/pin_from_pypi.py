"""Pin resolved requirements to the sha256 hashes PyPI itself publishes.

This host cannot reach files.pythonhosted.org (connections are reset) but can
reach pypi.org and public mirrors. Versions are resolved through a mirror;
this script then asks pypi.org's JSON API for every file of each pinned
release and writes a ``--require-hashes`` requirements file. Installing from
the mirror with that file fails on any byte that differs from PyPI, so the
mirror is trusted for availability only, never for content.

Run:
    uv pip compile training/requirements.in --index-url <mirror> \
        --python-version 3.12 --python-platform x86_64-pc-windows-msvc -o resolved.txt
    uv run --no-project --with httpx python scripts/pin_from_pypi.py resolved.txt \
        training/requirements.txt
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path
from typing import Any

PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"
_PINNED = re.compile(r"^([A-Za-z0-9._-]+)==([A-Za-z0-9.!+_-]+)$")
ATTEMPTS = 4


def parse_resolved(text: str) -> list[tuple[str, str]]:
    """(name, version) of every ``name==version`` line; comments and blanks skipped."""
    pins = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = _PINNED.match(line)
        if not match:
            raise ValueError(f"not an exact pin: {line!r}")
        pins.append((match.group(1).lower(), match.group(2)))
    return pins


def digests_from_release(release: dict[str, Any]) -> list[str]:
    """sha256 of every file PyPI lists for one release."""
    digests = [f["digests"]["sha256"] for f in release.get("urls", [])]
    if not digests:
        raise ValueError("release has no files on PyPI")
    return digests


def pinned_block(name: str, version: str, digests: list[str]) -> str:
    hashes = " \\\n".join(f"    --hash=sha256:{d}" for d in sorted(digests))
    return f"{name}=={version} \\\n{hashes}\n"


def header(source: Path) -> str:
    """Comment lines naming the file the pins were generated from."""
    return (
        f"# Generated by scripts/pin_from_pypi.py from {source.as_posix()}.\n"
        "# Hashes are PyPI's own (pypi.org JSON API); install with --require-hashes.\n"
    )


def fetch_release(client: Any, name: str, version: str) -> dict[str, Any]:
    for attempt in range(1, ATTEMPTS + 1):
        try:
            response = client.get(PYPI_JSON.format(name=name, version=version))
            response.raise_for_status()
            return response.json()
        except Exception:
            if attempt == ATTEMPTS:
                raise
            time.sleep(3 * attempt)
    raise AssertionError("unreachable")


def main() -> int:
    import httpx

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("resolved", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    pins = parse_resolved(args.resolved.read_text(encoding="utf-8"))
    blocks = []
    with httpx.Client(timeout=30, follow_redirects=True) as client:
        for name, version in sorted(pins):
            digests = digests_from_release(fetch_release(client, name, version))
            blocks.append(pinned_block(name, version, digests))
            print(f"{name}=={version}: {len(digests)} files", flush=True)
    args.output.write_text(header(args.resolved) + "".join(blocks), encoding="utf-8")
    print(f"{len(pins)} packages pinned to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
